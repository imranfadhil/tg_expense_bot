#!/usr/bin/env bash
set -euo pipefail

REMOTE_DIR="$1"
BOT_TOKEN="$2"
DEFAULT_CURRENCY="$3"
TIMEZONE="$4"
POSTGRES_USER="$5"
POSTGRES_DB="$6"
BOT_PASSPHRASE="${7:-}"
WEBAPP_PORT="${8:-8090}"
WEBAPP_URL="${9:-}"

cd "$REMOTE_DIR"

if [ ! -f .env ]; then
    cp .env.example .env
fi

# Generate a strong random POSTGRES_PASSWORD on first deploy and keep it across syncs
CURRENT_PG_PASS=$(grep -E '^POSTGRES_PASSWORD=' .env | cut -d'=' -f2- || true)
if [ -z "$CURRENT_PG_PASS" ] || [ "$CURRENT_PG_PASS" = "expense_secret_password" ]; then
    NEW_PG_PASS=$(openssl rand -hex 20)
else
    NEW_PG_PASS="$CURRENT_PG_PASS"
fi

cat > .env <<EOF
# Auto-generated by deploy/sync.bat
BOT_TOKEN=${BOT_TOKEN}
BOT_PASSPHRASE=${BOT_PASSPHRASE}
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${NEW_PG_PASS}
POSTGRES_DB=${POSTGRES_DB}
POSTGRES_HOST=db
POSTGRES_PORT=5432
DEFAULT_CURRENCY=${DEFAULT_CURRENCY}
TIMEZONE=${TIMEZONE}
WEBAPP_ENABLED=true
WEBAPP_PORT=${WEBAPP_PORT}
WEBAPP_URL=${WEBAPP_URL}
EOF

chmod 600 .env

